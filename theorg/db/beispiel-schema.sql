SET SQL DIALECT 3; 

/* CREATE DATABASE 'localhost/3051:BEISPIEL' PAGE_SIZE 8192 DEFAULT CHARACTER SET WIN1252 */


/*  Generators or sequences */
CREATE GENERATOR GEN_PATIENT;
CREATE GENERATOR GEN_PROTOKOLL;
CREATE GENERATOR GEN_REZEPT;
CREATE GENERATOR GEN_TERMIN;

/* Domain definitions */
CREATE DOMAIN D_JANEIN AS CHAR(1)
         DEFAULT 'N'
         CHECK (VALUE IN ('J', 'N'));
CREATE DOMAIN D_PATNR AS CHAR(10);

/* Table: ARBEITSPLATZ, Owner: SYSDBA */
CREATE TABLE ARBEITSPLATZ (AP_NAME VARCHAR(30) NOT NULL,
        AKT_PATNR D_PATNR,
        ANGEMELDET TIMESTAMP,
CONSTRAINT PK_ARBEITSPLATZ PRIMARY KEY (AP_NAME));

/* Table: ARBEITSZEIT, Owner: SYSDBA */
CREATE TABLE ARBEITSZEIT (AZ_ID INTEGER NOT NULL,
        TH_ID INTEGER NOT NULL,
        WOCHENTAG SMALLINT,
        VON TIME,
        BIS TIME,
        GUELTIG_AB DATE,
CONSTRAINT PK_ARBEITSZEIT PRIMARY KEY (AZ_ID));

/* Table: CHECKIN, Owner: SYSDBA */
CREATE TABLE CHECKIN (CHECKIN_ID BIGINT NOT NULL,
        PATNR D_PATNR,
        ZEITPUNKT TIMESTAMP,
        GERAET VARCHAR(20),
CONSTRAINT PK_CHECKIN PRIMARY KEY (CHECKIN_ID));

/* Table: DOKUMENT, Owner: SYSDBA */
CREATE TABLE DOKUMENT (DOK_ID INTEGER NOT NULL,
        PATNR D_PATNR,
        ART CHAR(3),
        TITEL VARCHAR(80),
        INHALT BLOB SUB_TYPE 0 SEGMENT SIZE 80,
        ANGELEGT TIMESTAMP,
CONSTRAINT PK_DOKUMENT PRIMARY KEY (DOK_ID));

/* Table: KONFIG, Owner: SYSDBA */
CREATE TABLE KONFIG (SCHLUESSEL VARCHAR(40) NOT NULL,
        WERT VARCHAR(200),
        MODUL VARCHAR(20),
CONSTRAINT PK_KONFIG PRIMARY KEY (SCHLUESSEL));

/* Table: KURS, Owner: SYSDBA */
CREATE TABLE KURS (KURS_ID INTEGER NOT NULL,
        BEZEICHNUNG VARCHAR(60),
        ART CHAR(2),
        TH_ID INTEGER,
        WOCHENTAG SMALLINT,
        BEGINN TIME,
        PLAETZE SMALLINT,
        "POSITION" SMALLINT,
CONSTRAINT PK_KURS PRIMARY KEY (KURS_ID));

/* Table: MANDANT, Owner: SYSDBA */
CREATE TABLE MANDANT (MANDANT_NR SMALLINT NOT NULL,
        BEZEICHNUNG VARCHAR(60),
        IK CHAR(9),
        AKTIV D_JANEIN,
CONSTRAINT PK_MANDANT PRIMARY KEY (MANDANT_NR));

/* Table: OPOSTEN, Owner: SYSDBA */
CREATE TABLE OPOSTEN (OP_ID INTEGER NOT NULL,
        PATNR D_PATNR,
        BELEGNR VARCHAR(12),
        BETRAG VARCHAR(12),
        OFFEN VARCHAR(12),
        STORNO D_JANEIN,
        BELEGDATUM CHAR(8),
CONSTRAINT PK_OPOSTEN PRIMARY KEY (OP_ID));

/* Table: PATIENT, Owner: SYSDBA */
CREATE TABLE PATIENT (PATNR D_PATNR NOT NULL,
        MANDANT_NR SMALLINT NOT NULL,
        NAME VARCHAR(40),
        VORNAME VARCHAR(30),
        GEBDAT CHAR(8),
        GESCHLECHT CHAR(1),
        STRASSE VARCHAR(50),
        PLZ CHAR(5),
        ORT VARCHAR(40),
        TELEFON VARCHAR(30),
        EMAIL VARCHAR(80),
        KASSE_IK CHAR(9),
        VERSNR VARCHAR(12),
        ANGELEGT TIMESTAMP,
        GEAENDERT TIMESTAMP,
        GESPERRT D_JANEIN,
CONSTRAINT PK_PATIENT PRIMARY KEY (PATNR));

/* Table: PROTOKOLL, Owner: SYSDBA */
CREATE TABLE PROTOKOLL (PROT_ID INTEGER NOT NULL,
        TABELLE VARCHAR(31),
        AKTION CHAR(1),
        ZEITPUNKT TIMESTAMP,
        INFO BLOB SUB_TYPE TEXT SEGMENT SIZE 80,
CONSTRAINT PK_PROTOKOLL PRIMARY KEY (PROT_ID));

/* Table: REZEPT, Owner: SYSDBA */
CREATE TABLE REZEPT (REZEPT_ID INTEGER NOT NULL,
        PATNR D_PATNR,
        AUSSTELLUNG CHAR(8),
        ARZT_LANR CHAR(9),
        HEILMITTEL VARCHAR(10),
        EINHEITEN SMALLINT,
        ERBRACHT SMALLINT,
        ZUZAHLUNG VARCHAR(12),
        BEFREIT D_JANEIN,
        STATUS CHAR(1),
        OFFEN_EINHEITEN COMPUTED BY (EINHEITEN - ERBRACHT),
CONSTRAINT PK_REZEPT PRIMARY KEY (REZEPT_ID));

/* Table: TERMIN, Owner: SYSDBA */
CREATE TABLE TERMIN (TERMIN_ID INTEGER NOT NULL,
        MANDANT_NR SMALLINT,
        PATNR D_PATNR,
        TH_ID INTEGER,
        SPALTE SMALLINT,
        DATUM DATE,
        VON TIME,
        DAUER SMALLINT,
        STATUS CHAR(1),
        REZEPT_ID INTEGER,
        SERIE_ID INTEGER,
        BEMERKUNG VARCHAR(200),
        AENDERUNG TIMESTAMP,
        ARBEITSPLATZ VARCHAR(20),
CONSTRAINT PK_TERMIN PRIMARY KEY (TERMIN_ID));

/* Table: THERAPEUT, Owner: SYSDBA */
CREATE TABLE THERAPEUT (TH_ID INTEGER NOT NULL,
        MANDANT_NR SMALLINT NOT NULL,
        KUERZEL VARCHAR(4),
        NAME VARCHAR(40),
        VORNAME VARCHAR(30),
        FARBE INTEGER,
        SPALTE SMALLINT,
        AKTIV D_JANEIN,
CONSTRAINT PK_THERAPEUT PRIMARY KEY (TH_ID));

/* Table: VERTRAG, Owner: SYSDBA */
CREATE TABLE VERTRAG (VERTRAG_ID INTEGER NOT NULL,
        PATNR D_PATNR,
        MODUL VARCHAR(20),
        BEGINN DATE,
        ENDE DATE,
        KUENDIGUNG DATE,
        BEITRAG NUMERIC(9, 2),
        STATUS CHAR(1),
CONSTRAINT PK_VERTRAG PRIMARY KEY (VERTRAG_ID));

/*  Index definitions for all user tables */
CREATE INDEX IX_TERMIN_DATUM ON TERMIN (DATUM);
CREATE UNIQUE INDEX UX_THERAPEUT_KUERZEL ON THERAPEUT (MANDANT_NR, KUERZEL);

ALTER TABLE ARBEITSZEIT ADD CONSTRAINT FK_ARBEITSZEIT_TH FOREIGN KEY (TH_ID) REFERENCES THERAPEUT (TH_ID);

ALTER TABLE TERMIN ADD CONSTRAINT FK_TERMIN_TH FOREIGN KEY (TH_ID) REFERENCES THERAPEUT (TH_ID);

/* View: V_TERMIN_OFFEN, Owner: SYSDBA */
CREATE VIEW V_TERMIN_OFFEN (TERMIN_ID, PATNR, TH_ID, DATUM, VON) AS

  SELECT TERMIN_ID, PATNR, TH_ID, DATUM, VON FROM TERMIN WHERE STATUS IS NULL OR STATUS = ' ';
COMMIT WORK;
SET AUTODDL OFF;
SET TERM ^ ;

/* Stored procedures */
CREATE PROCEDURE NAECHSTE_PATNR RETURNS (PATNR CHAR(10) CHARACTER SET WIN1252)
AS 
BEGIN SUSPEND; END ^

ALTER PROCEDURE NAECHSTE_PATNR RETURNS (PATNR CHAR(10) CHARACTER SET WIN1252)
AS 
BEGIN
  PATNR = LPAD(CAST(GEN_ID(GEN_PATIENT, 1) AS VARCHAR(10)), 10, ' ');
  SUSPEND;
END ^
SET TERM ; ^
COMMIT WORK ;
SET AUTODDL ON;
SET TERM ^ ;

/* Triggers only will work for SQL triggers */
CREATE TRIGGER PATIENT_BU FOR PATIENT 
ACTIVE BEFORE UPDATE POSITION 0 
AS
BEGIN
  NEW.GEAENDERT = CURRENT_TIMESTAMP;
END ^

CREATE TRIGGER TERMIN_BI FOR TERMIN 
ACTIVE BEFORE INSERT POSITION 0 
AS
BEGIN
  IF (NEW.TERMIN_ID IS NULL) THEN NEW.TERMIN_ID = GEN_ID(GEN_TERMIN, 1);
  NEW.AENDERUNG = CURRENT_TIMESTAMP;
END ^

CREATE TRIGGER TERMIN_AIU FOR TERMIN 
ACTIVE AFTER INSERT OR UPDATE POSITION 10 
AS
BEGIN
  INSERT INTO PROTOKOLL (PROT_ID, TABELLE, AKTION, ZEITPUNKT) VALUES (GEN_ID(GEN_PROTOKOLL, 1), 'TERMIN', 'S', CURRENT_TIMESTAMP);
  POST_EVENT 'TERMIN_GEAENDERT';
END ^

COMMIT WORK ^
SET TERM ; ^
